"""The committed serving artifacts must stay loadable under the locked deps.

model_artifacts/*.pkl are pickles that record the library version that wrote
them. scikit-learn raises InconsistentVersionWarning and XGBoost raises a
model-format UserWarning when the running version differs, so "loads without
those warnings" is a precise, self-checking compatibility contract.

Warnings are recorded with simplefilter("always") and asserted on. Nothing here
suppresses them, and nothing is marked xfail: if a dependency bump makes an
artifact incompatible, these tests fail and the choice becomes explicit -
revert the bump, or retrain and recommit the artifacts.
"""
import re
import warnings
from pathlib import Path

import joblib
import pandas as pd
import pytest
import sklearn
import xgboost

from conftest import ARTIFACTS_DIR, REPO_ROOT, VALID_PAYLOAD

# Artifacts actually loaded by app.py / streamlit_app.py / admin_app.py.
SERVING_ARTIFACTS = [
    "model_bundle.pkl",
    "boosted_model_bundle.pkl",
    "shap_explainer.pkl",
    "boosted_shap_explainer.pkl",
    "drift_baseline.pkl",
    "boosted_drift_baseline.pkl",
]

# Present in model_artifacts/ but referenced by no serving module. They were
# written by scikit-learn 1.7.1 and would raise InconsistentVersionWarning, so
# they must not be used to define the serving compatibility contract.
UNSERVED_ARTIFACTS = ["diabetes_model.pkl", "scaler.pkl"]

SERVING_MODULES = ["app.py", "streamlit_app.py", "admin_app.py"]

# Substrings identifying a serialization-version mismatch, whatever the
# warning category.
MISMATCH_MARKERS = (
    "InconsistentVersionWarning",
    "Trying to unpickle estimator",
    "older version of XGBoost",
    "generated by an older version",
)


def _record_warnings(load):
    """Run `load`, returning (result, [formatted warnings])."""
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        result = load()
    return result, [f"{w.category.__name__}: {w.message}" for w in caught]


def _mismatches(messages):
    return [m for m in messages if any(marker in m for marker in MISMATCH_MARKERS)]


def _pinned_version(package: str) -> str:
    """Read an exact `package==X.Y.Z` pin out of requirements.txt."""
    text = (REPO_ROOT / "requirements.txt").read_text(encoding="utf-8")
    match = re.search(rf"^{re.escape(package)}==([0-9][^\s#]*)", text, re.MULTILINE)
    assert match, f"{package} is not exactly pinned in requirements.txt"
    return match.group(1)


@pytest.mark.parametrize("artifact", SERVING_ARTIFACTS)
def test_serving_artifact_is_present(artifact):
    assert (ARTIFACTS_DIR / artifact).is_file(), f"{artifact} missing from a fresh clone"


@pytest.mark.parametrize("artifact", SERVING_ARTIFACTS)
def test_serving_artifact_loads_without_version_mismatch(artifact):
    _, messages = _record_warnings(lambda: joblib.load(ARTIFACTS_DIR / artifact))

    assert _mismatches(messages) == [], (
        f"{artifact} is not compatible with the locked dependency set. "
        f"Running scikit-learn {sklearn.__version__}, xgboost {xgboost.__version__}."
    )


def test_installed_sklearn_matches_the_artifact_pin():
    """The artifacts carry _sklearn_version 1.8.0; the pin must not drift."""
    assert sklearn.__version__ == _pinned_version("scikit-learn")


def test_installed_xgboost_matches_the_artifact_pin():
    """The pickled booster records UBJSON version [3, 0, 4]."""
    assert xgboost.__version__.split("+")[0] == _pinned_version("xgboost")


@pytest.mark.parametrize(
    ("bundle_name", "model_name"),
    [("model_bundle.pkl", "logistic_regression"),
     ("boosted_model_bundle.pkl", "xgboost_boosted_trees")],
)
def test_loaded_pipeline_still_scores(bundle_name, model_name):
    """Loading cleanly is not enough - the estimator must still predict."""
    bundle = joblib.load(ARTIFACTS_DIR / bundle_name)
    frame = pd.DataFrame([VALID_PAYLOAD])[bundle["feature_columns"]]

    proba, messages = _record_warnings(
        lambda: float(bundle["pipeline"].predict_proba(frame)[:, 1][0])
    )

    assert bundle["model_name"] == model_name
    assert 0.0 <= proba <= 1.0
    assert _mismatches(messages) == []


@pytest.mark.parametrize(
    ("shap_name", "bundle_name"),
    [("shap_explainer.pkl", "model_bundle.pkl"),
     ("boosted_shap_explainer.pkl", "boosted_model_bundle.pkl")],
)
def test_shap_explainer_still_explains(shap_name, bundle_name):
    """SHAP explainers pickle shap's own classes, so they drift with shap too."""
    shap_bundle = joblib.load(ARTIFACTS_DIR / shap_name)
    columns = joblib.load(ARTIFACTS_DIR / bundle_name)["feature_columns"]
    frame = pd.DataFrame([VALID_PAYLOAD])[columns]

    values, messages = _record_warnings(
        lambda: shap_bundle["explainer"].shap_values(frame)
    )

    if isinstance(values, list):
        values = values[1]
    assert len(values[0]) == len(columns)
    assert _mismatches(messages) == []


@pytest.mark.parametrize("artifact", UNSERVED_ARTIFACTS)
def test_unserved_artifacts_are_referenced_by_no_serving_module(artifact):
    """These are scikit-learn 1.7.1 leftovers.

    They are excluded from the compatibility contract above precisely because
    nothing serves them. If a serving module ever starts loading one, this test
    fails and the contract has to be widened (or the artifact retrained).
    """
    for module in SERVING_MODULES:
        source = (REPO_ROOT / module).read_text(encoding="utf-8")
        assert artifact not in source, f"{module} now loads unserved artifact {artifact}"


@pytest.mark.parametrize("variant", ["A", "B"])
def test_drift_check_reads_the_committed_baseline(client, valid_payload, variant):
    """Exercises both on-disk baseline formats through the real endpoint.

    Variant A stores {feature: {mean, std, ...}}; variant B stores
    {feature_columns, means, stds, ...}. app.py branches on that difference.
    """
    response = client.post("/drift-check", json=valid_payload, params={"model_variant": variant})

    assert response.status_code == 200
    body = response.json()
    assert body["model_variant"] == variant
    assert body["total_features"] == 10
    assert len(body["feature_drift"]) == 10
    assert body["outlier_count"] == sum(item["is_outlier"] for item in body["feature_drift"])
    assert body["drift_detected"] is (body["outlier_count"] > 0)

    for item in body["feature_drift"]:
        assert item["feature"] in valid_payload
        assert item["training_std"] > 0
        expected_z = (item["value"] - item["training_mean"]) / item["training_std"]
        assert item["z_score"] == pytest.approx(expected_z, abs=1e-3)


def test_drift_baseline_endpoint_returns_every_feature(client):
    response = client.get("/drift-baseline", params={"model_variant": "A"})

    assert response.status_code == 200
    baseline = response.json()["baseline"]
    assert sorted(baseline) == sorted(VALID_PAYLOAD)


def test_lockfile_pins_every_requirement_exactly():
    """requirements.lock.txt is the reproducible install; no floating entries."""
    lock = (REPO_ROOT / "requirements.lock.txt").read_text(encoding="utf-8")
    floating = [
        line for line in lock.splitlines()
        if line and not line.startswith(("#", " ", "\t")) and "==" not in line
    ]
    assert floating == []


def test_lockfile_agrees_with_the_artifact_pins():
    lock = (REPO_ROOT / "requirements.lock.txt").read_text(encoding="utf-8")
    for package in ("scikit-learn", "xgboost"):
        pin = _pinned_version(package)
        assert re.search(rf"^{re.escape(package)}=={re.escape(pin)}(\s|$|;)", lock, re.MULTILINE), (
            f"requirements.lock.txt does not pin {package}=={pin}"
        )


def test_repository_ships_no_python_bytecode():
    """Compiled bytecode was untracked in Track B; it must not come back."""
    tracked = [
        line for line in
        (REPO_ROOT / ".gitignore").read_text(encoding="utf-8").splitlines()
    ]
    assert "__pycache__/" in tracked
    assert "*.pyc" in tracked
    assert not list(Path(REPO_ROOT).glob("*.pyc"))
